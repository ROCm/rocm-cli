//! Reading the PEP 751 `pylock.toml` files `uv pip compile` writes, and giving
//! them the header `deps check` expects.

use std::collections::BTreeMap;

use anyhow::{Context, Result, ensure};
use serde::Deserialize;

/// A lock as `deps check` and `deps diff` read it. The fields uv writes for
/// the current profiles are named here, and any other is refused
/// (`deny_unknown_fields`), as in
/// `mise.lock`: a field this tooling does not know might change what gets
/// installed without `deps check` looking at it.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub(crate) struct PyLock {
    pub(crate) lock_version: String,
    /// The tool that wrote the lock; not checked.
    #[serde(default, rename = "created-by")]
    pub(crate) _created_by: Option<String>,
    /// The Python range of the lock; the profile's Python is checked per
    /// wheel instead.
    #[serde(default, rename = "requires-python")]
    pub(crate) _requires_python: Option<String>,
    #[serde(default)]
    pub(crate) packages: Vec<Package>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub(crate) struct Package {
    pub(crate) name: String,
    pub(crate) version: Option<String>,
    /// The environments the package is installed in; only narrows them.
    #[serde(default, rename = "marker")]
    pub(crate) _marker: Option<String>,
    #[serde(default)]
    pub(crate) wheels: Vec<Artifact>,
    pub(crate) sdist: Option<Artifact>,
    /// PEP 751's other sources. `deps check` refuses any package that names
    /// one: only `wheels` and `sdist` are held to its host and hash rules.
    pub(crate) vcs: Option<toml::Value>,
    pub(crate) directory: Option<toml::Value>,
    pub(crate) archive: Option<toml::Value>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub(crate) struct Artifact {
    pub(crate) url: Option<String>,
    #[serde(default)]
    pub(crate) hashes: BTreeMap<String, String>,
    /// Index metadata; the hash, not these, identifies the file.
    #[serde(default, rename = "upload-time")]
    pub(crate) _upload_time: Option<toml::Value>,
    #[serde(default, rename = "size")]
    pub(crate) _size: Option<u64>,
}

impl PyLock {
    pub(crate) fn parse(text: &str) -> Result<Self> {
        let lock: Self = toml::from_str(text).context("not a valid pylock.toml")?;
        ensure!(
            lock.lock_version == "1.0",
            "unsupported lock-version {:?} (expected 1.0)",
            lock.lock_version
        );
        Ok(lock)
    }
}

/// A PEP 508 name: ASCII letters, digits, `-`, `_` and `.`, starting and
/// ending alphanumeric. `deps check` refuses any other, and `deps diff` will
/// not render one, since the name goes as-is into the update's Markdown table.
pub(crate) fn is_valid_name(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_alphanumeric())
        && name.ends_with(|c: char| c.is_ascii_alphanumeric())
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
}

/// PEP 440's characters only (ASCII letters, digits, `. + ! _ -`), starting
/// with a digit. Not the full grammar: what matters is that the version, too,
/// goes as-is into the update's Markdown table.
pub(crate) fn is_valid_version(version: &str) -> bool {
    version.starts_with(|c: char| c.is_ascii_digit())
        && version
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '+' | '!' | '_' | '-'))
}

impl Package {
    /// The PEP 751 source keys this package uses besides `wheels`/`sdist`.
    pub(crate) fn unchecked_sources(&self) -> Vec<&'static str> {
        [
            ("vcs", self.vcs.is_some()),
            ("directory", self.directory.is_some()),
            ("archive", self.archive.is_some()),
        ]
        .into_iter()
        .filter_map(|(key, present)| present.then_some(key))
        .collect()
    }

    /// Every artifact this package can be installed from.
    pub(crate) fn artifacts(&self) -> impl Iterator<Item = &Artifact> {
        self.wheels.iter().chain(self.sdist.as_ref())
    }
}

/// The header every committed lock starts with. `deps check` compares it
/// verbatim, so a lock edited by hand or written by a bare `uv pip compile`
/// (whose header records a machine-local command line) is caught.
pub(crate) fn header(profile: &str, os: &str) -> String {
    format!(
        "# Generated by `cargo xtask deps lock` from runtimes/profiles.toml\n\
         # (profile `{profile}`, {os}). Do not edit; see docs/runtime-dependencies.md.\n"
    )
}

/// The header line recording the `--exclude-newer` cutoff the lock was
/// resolved at; an ordinary re-lock resolves at the same cutoff.
pub(crate) fn cutoff_line(cutoff: &str) -> String {
    format!("# exclude-newer: {cutoff}\n")
}

/// The cutoff a lock records, if its header carries a valid one.
pub(crate) fn recorded_cutoff(text: &str) -> Option<String> {
    text.lines()
        .take_while(|line| line.starts_with('#'))
        .find_map(|line| line.strip_prefix("# exclude-newer: "))
        .filter(|cutoff| chrono::DateTime::parse_from_rfc3339(cutoff).is_ok())
        .map(str::to_owned)
}

/// Whether two locks differ at most in their `# exclude-newer:` header line.
pub(crate) fn same_but_cutoff(a: &str, b: &str) -> bool {
    let without = |text: &str| -> Vec<String> {
        text.lines()
            .filter(|line| !line.starts_with("# exclude-newer: "))
            .map(str::to_owned)
            .collect()
    };
    without(a) == without(b)
}

/// The header line recording what the lock was resolved from (see
/// `Profiles::inputs_digest`).
pub(crate) fn inputs_line(digest: &str) -> String {
    format!("# inputs: sha256:{digest}\n")
}

/// Turn uv's output (written with `--no-header`) into the committed lock.
/// Refuses a lock that points at a local file: a committed lock must be
/// installable on any machine.
pub(crate) fn finalize(
    raw: &str,
    profile: &str,
    os: &str,
    inputs: &str,
    cutoff: &str,
) -> Result<String> {
    ensure!(
        !raw.contains("\"file://"),
        "uv wrote a local file:// artifact into the {profile}/{os} lock"
    );
    Ok(format!(
        "{}{}{}{}",
        header(profile, os),
        inputs_line(inputs),
        cutoff_line(cutoff),
        raw.trim_start_matches('\n')
    ))
}

/// Host of an `https://` URL, if it is one.
pub(crate) fn https_host(url: &str) -> Option<&str> {
    let rest = url.strip_prefix("https://")?;
    // URL parsers disagree on `\\` before the host (WHATWG treats it as `/`),
    // so a URL that relies on one is refused rather than guessed at.
    if rest.split(['/', '?', '#']).next()?.contains('\\') {
        return None;
    }
    let authority = rest.split(['/', '?', '#']).next()?;
    let host = authority
        .rsplit_once('@')
        .map_or(authority, |(_, host)| host);
    let host = host.split(':').next().unwrap_or(host);
    (!host.is_empty()).then_some(host)
}

#[cfg(test)]
mod tests {
    use super::*;

    const RAW: &str = r#"lock-version = "1.0"
created-by = "uv"
requires-python = ">=3.14"

[[packages]]
name = "rocm"
version = "10.1.0"
sdist = { url = "https://stable.repo.amd.com/rocm/whl-next/rocm/rocm-10.1.0.tar.gz", hashes = { sha256 = "bb" } }

[[packages]]
name = "numpy"
version = "2.3.0"
wheels = [{ url = "https://files.pythonhosted.org/numpy-2.3.0-cp314-cp314-win_amd64.whl", hashes = { sha256 = "aa" } }]
"#;

    /// Blank lines at the start of uv's output do not end up between our
    /// header and the lock body.
    #[test]
    fn finalize_drops_leading_blank_lines() {
        let out = finalize(
            &format!("\n\n{RAW}"),
            "p",
            "linux",
            "ab",
            "2026-10-30T12:00:00Z",
        )
        .unwrap();
        assert_eq!(
            out,
            format!(
                "{}# inputs: sha256:ab\n# exclude-newer: 2026-10-30T12:00:00Z\n{RAW}",
                header("p", "linux")
            )
        );
    }

    #[test]
    fn the_recorded_cutoff_is_read_only_from_the_header_and_only_if_valid() {
        let lock = finalize(RAW, "p", "linux", "ab", "2026-10-30T12:00:00Z").unwrap();
        assert_eq!(
            recorded_cutoff(&lock).as_deref(),
            Some("2026-10-30T12:00:00Z")
        );
        assert_eq!(recorded_cutoff(RAW), None);
        let invalid = lock.replace("2026-10-30T12:00:00Z", "last week");
        assert_eq!(recorded_cutoff(&invalid), None);
        // A line in the body is not the header's.
        let in_body = format!("{RAW}# exclude-newer: 2026-10-30T12:00:00Z\n");
        assert_eq!(recorded_cutoff(&in_body), None);
    }

    #[test]
    fn finalize_prepends_the_header_and_keeps_the_body() {
        let out = finalize(RAW, "p", "windows", "ab", "2026-10-30T12:00:00Z").unwrap();
        assert!(out.starts_with(&header("p", "windows")));
        let lock = PyLock::parse(&out).unwrap();
        assert_eq!(lock.packages.len(), 2);
        assert_eq!(
            lock.packages[0].sdist.as_ref().unwrap().hashes["sha256"],
            "bb"
        );
        assert_eq!(lock.packages[1].artifacts().count(), 1);
    }

    #[test]
    fn a_local_artifact_is_refused() {
        let raw = RAW.replace("https://files.pythonhosted.org/", "file:///home/u/wheels/");
        assert!(finalize(&raw, "p", "linux", "ab", "2026-10-30T12:00:00Z").is_err());
    }

    #[test]
    fn an_unknown_lock_version_is_refused() {
        assert!(PyLock::parse(&RAW.replace("\"1.0\"", "\"2.0\"")).is_err());
    }

    #[test]
    fn hosts_are_extracted_from_https_urls_only() {
        // No host at all is not an https URL.
        assert_eq!(https_host("https:///x.whl"), None);
        assert_eq!(https_host("https://u@/x.whl"), None);
        assert_eq!(
            https_host("https://stable.repo.amd.com/rocm/x.whl"),
            Some("stable.repo.amd.com")
        );
        assert_eq!(
            https_host("https://u@host.example:443/x"),
            Some("host.example")
        );
        // Userinfo that mimics a vendor host must not pass as that host.
        assert_eq!(
            https_host("https://stable.repo.amd.com@evil.example/x"),
            Some("evil.example")
        );
        // The host follows the last `@`, however many the userinfo holds.
        assert_eq!(
            https_host("https://a@b@evil.example/x"),
            Some("evil.example")
        );
        assert_eq!(
            https_host("https://evil.example\\@stable.repo.amd.com/x"),
            None
        );
        assert_eq!(https_host("http://stable.repo.amd.com/x"), None);
        assert_eq!(https_host("file:///x"), None);
    }
}
