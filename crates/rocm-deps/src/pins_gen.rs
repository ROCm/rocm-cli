//! Turn `runtimes/mise.lock` into Rust constants.
//!
//! Shared by `build.rs`, which includes this file by path and writes the
//! result to `$OUT_DIR/pins.rs`; by this crate's tests, which exercise it
//! directly — a build script cannot be unit-tested on its own; and by
//! `cargo xtask deps check`, so a lock the check accepts is one the build
//! accepts.
//!
//! Every runtime tool in the lock becomes `<NAME>_VERSION`, and each platform
//! `<NAME>_<PLATFORM>_URL` and `<NAME>_<PLATFORM>_SHA256` (hex). `<NAME>` is
//! the tool's last path segment upper-cased (`github:lemonade-sdk/lemonade`
//! -> `LEMONADE_VERSION`, `LEMONADE_LINUX_X64_SHA256`).

use std::collections::BTreeMap;
use std::fmt::Write as _;

/// The lock format this generator understands.
pub const LOCKFILE_VERSION: i64 = 3;

/// Platforms every runtime tool must be locked for: rocm-cli runs on exactly
/// these, and a consumer selecting a constant by host must find one.
pub const REQUIRED_PLATFORMS: [&str; 2] = ["linux-x64", "windows-x64"];

/// uv as `runtimes/mise.toml` names it: `cargo xtask deps lock` resolves the
/// Python locks with this tool.
pub const UV_TOOL: &str = "aqua:astral-sh/uv";

/// Tools pinned for the repository's own tooling rather than downloaded by
/// rocm-cli. No constants are generated for them, so nothing can come to
/// depend on a pin that was not chosen with users in mind.
pub const TOOLING_ONLY: [&str; 1] = [UV_TOOL];

/// Render the constants for one lock, or say what is wrong with it.
pub fn render(text: &str) -> Result<String, String> {
    let doc: toml::Table = toml::from_str(text).map_err(|err| format!("not valid TOML: {err}"))?;
    let version = doc
        .get("lockfile_version")
        .and_then(toml::Value::as_integer);
    if version != Some(LOCKFILE_VERSION) {
        return Err(format!(
            "lockfile_version is {version:?}; this generator reads version {LOCKFILE_VERSION}"
        ));
    }
    let tools = doc
        .get("tools")
        .and_then(toml::Value::as_table)
        .ok_or("no [tools] table")?;

    let mut out = String::from(
        "// @generated by build.rs from runtimes/mise.lock -- do not edit; edit runtimes/mise.toml.\n",
    );
    // Two tools can share a last path segment (`github:a/x`, `aqua:b/x`).
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for (tool, entries) in tools {
        if TOOLING_ONLY.contains(&tool.as_str()) {
            continue;
        }
        // The name ends up in generated comments and identifiers, so it may
        // hold nothing that could end a comment line or an identifier early.
        if tool.is_empty()
            || !tool
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | ':' | '/' | '-'))
        {
            return Err(format!(
                "tool name {tool:?} has characters a pin cannot carry"
            ));
        }
        let ident = const_ident(tool);
        if !ident.starts_with(|c: char| c.is_ascii_uppercase()) {
            return Err(format!(
                "tool {tool:?} folds to {ident:?}, which is not a Rust identifier"
            ));
        }
        if let Some(previous) = seen.insert(ident.clone(), tool) {
            return Err(format!(
                "tools {previous:?} and {tool:?} both generate {ident}_*"
            ));
        }
        let version = locked_version(tool, entries)?;
        let assets = locked_assets(tool, entries)?;
        for platform in REQUIRED_PLATFORMS {
            if !assets.contains_key(platform) {
                return Err(format!("{tool} is not locked for {platform}"));
            }
        }
        writeln!(
            out,
            "/// Version of `{tool}` locked in `runtimes/mise.lock`.\npub const {ident}_VERSION: &str = {version:?};"
        )
        .expect("writing to a String cannot fail");
        for (platform, (url, sha256)) in assets {
            let prefix = format!("{ident}_{}", platform.to_uppercase().replace('-', "_"));
            writeln!(
                out,
                "/// Download URL of `{tool}` for `{platform}`, from `runtimes/mise.lock`.\n\
                 pub const {prefix}_URL: &str = {url:?};\n\
                 /// Hex SHA-256 of that download, from `runtimes/mise.lock`.\n\
                 pub const {prefix}_SHA256: &str = {sha256:?};"
            )
            .expect("writing to a String cannot fail");
        }
    }
    Ok(out)
}

/// The single version every entry of `tool` locks. mise writes one entry per
/// option set (one per platform when assets are chosen per platform); all of
/// them must agree.
fn locked_version<'a>(tool: &str, entries: &'a toml::Value) -> Result<&'a str, String> {
    let entries = entries
        .as_array()
        .ok_or_else(|| format!("tools.{tool:?} must be an array of entries"))?;
    let mut version: Option<&str> = None;
    for entry in entries {
        let this = entry
            .get("version")
            .and_then(toml::Value::as_str)
            .ok_or_else(|| format!("tools.{tool:?} has an entry without a version"))?;
        match version {
            Some(previous) if previous != this => {
                return Err(format!(
                    "tools.{tool:?} locks two versions ({previous} and {this})"
                ));
            }
            _ => version = Some(this),
        }
    }
    version.ok_or_else(|| format!("tools.{tool:?} has no entries"))
}

/// `platform -> (url, sha256)` for every platform `tool` is locked for. An
/// entry's platform tables are keyed `platforms.<os>-<arch>`.
fn locked_assets<'a>(
    tool: &str,
    entries: &'a toml::Value,
) -> Result<BTreeMap<&'a str, (&'a str, &'a str)>, String> {
    let mut assets = BTreeMap::new();
    for entry in entries.as_array().into_iter().flatten() {
        for (key, value) in entry.as_table().into_iter().flatten() {
            let Some(platform) = key.strip_prefix("platforms.") else {
                continue;
            };
            // Only the platforms rocm-cli supports: any other key would be
            // turned into a constant name, and is checked by nothing else.
            if !REQUIRED_PLATFORMS.contains(&platform) {
                return Err(format!(
                    "tools.{tool:?} locks {platform:?}; only {REQUIRED_PLATFORMS:?} are supported"
                ));
            }
            let field = |name: &str| {
                value
                    .get(name)
                    .and_then(toml::Value::as_str)
                    .ok_or_else(|| format!("tools.{tool:?} {key} has no {name}"))
            };
            let url = field("url")?;
            if !url.starts_with("https://") {
                return Err(format!("tools.{tool:?} {key} url is not https: {url}"));
            }
            let sha256 = field("checksum")?
                .strip_prefix("sha256:")
                .filter(|hex| {
                    hex.len() == 64 && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
                })
                .ok_or_else(|| {
                    format!("tools.{tool:?} {key} checksum is not a sha256 hex digest")
                })?;
            if assets.insert(platform, (url, sha256)).is_some() {
                return Err(format!("tools.{tool:?} locks {platform} twice"));
            }
        }
    }
    Ok(assets)
}

/// `github:lemonade-sdk/lemonade` -> `LEMONADE`: the last path segment,
/// upper-cased, with separators folded to `_`.
fn const_ident(tool: &str) -> String {
    let name = tool.rsplit(['/', ':']).next().unwrap_or(tool);
    name.to_uppercase().replace(['-', '.'], "_")
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUM: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

    fn entry(tool: &str, version: &str, platform: &str, url: &str, checksum: &str) -> String {
        format!(
            "[[tools.\"{tool}\"]]\nversion = \"{version}\"\n\n\
             [tools.\"{tool}\".\"platforms.{platform}\"]\nchecksum = \"{checksum}\"\nurl = \"{url}\"\n\n"
        )
    }

    fn lock(windows_version: &str) -> String {
        format!(
            "lockfile_version = 3\n\n{}{}{}",
            entry(
                "github:o/demo",
                "1.0",
                "linux-x64",
                "https://x/demo-linux.tar.gz",
                &format!("sha256:{SUM}")
            ),
            entry(
                "github:o/demo",
                windows_version,
                "windows-x64",
                "https://x/demo-windows.zip",
                &format!("sha256:{SUM}")
            ),
            entry(
                UV_TOOL,
                "0.13.6",
                "linux-x64",
                "https://x/uv.tar.gz",
                &format!("sha256:{SUM}")
            ),
        )
    }

    #[test]
    fn a_complete_lock_renders_version_url_and_digest_per_platform() {
        let out = render(&lock("1.0")).unwrap();
        assert!(
            out.contains("pub const DEMO_VERSION: &str = \"1.0\";"),
            "{out}"
        );
        assert!(
            out.contains("pub const DEMO_LINUX_X64_URL: &str = \"https://x/demo-linux.tar.gz\";")
        );
        assert!(out.contains(&format!(
            "pub const DEMO_WINDOWS_X64_SHA256: &str = \"{SUM}\";"
        )));
    }

    #[test]
    fn tooling_only_pins_generate_nothing() {
        let out = render(&lock("1.0")).unwrap();
        assert!(!out.contains("UV_"), "{out}");
    }

    #[test]
    fn entries_disagreeing_on_the_version_are_refused() {
        let err = render(&lock("1.1")).unwrap_err();
        assert!(err.contains("locks two versions"), "{err}");
    }

    #[test]
    fn a_missing_platform_is_refused() {
        let text = format!(
            "lockfile_version = 3\n\n{}",
            entry(
                "github:o/demo",
                "1.0",
                "linux-x64",
                "https://x/a",
                &format!("sha256:{SUM}")
            )
        );
        let err = render(&text).unwrap_err();
        assert!(err.contains("not locked for windows-x64"), "{err}");
    }

    #[test]
    fn an_unknown_lockfile_version_is_refused() {
        let err = render(&lock("1.0").replace("lockfile_version = 3", "lockfile_version = 4"))
            .unwrap_err();
        assert!(err.contains("lockfile_version"), "{err}");
    }

    #[test]
    fn a_non_sha256_or_malformed_checksum_is_refused() {
        let md5 = lock("1.0").replacen(&format!("sha256:{SUM}"), "md5:abc", 1);
        assert!(
            render(&md5)
                .unwrap_err()
                .contains("not a sha256 hex digest")
        );
        let short = lock("1.0").replacen(&format!("sha256:{SUM}"), "sha256:abc", 1);
        assert!(
            render(&short)
                .unwrap_err()
                .contains("not a sha256 hex digest")
        );
    }

    #[test]
    fn a_missing_url_or_plain_http_is_refused() {
        let no_url = lock("1.0").replacen("url = \"https://x/demo-linux.tar.gz\"\n", "", 1);
        assert!(render(&no_url).unwrap_err().contains("has no url"));
        let http = lock("1.0").replacen("https://x/demo-linux", "http://x/demo-linux", 1);
        assert!(render(&http).unwrap_err().contains("not https"));
    }

    #[test]
    fn a_platform_locked_twice_is_refused() {
        let text = lock("1.0").replacen("platforms.windows-x64", "platforms.linux-x64", 1);
        assert!(render(&text).unwrap_err().contains("locks linux-x64 twice"));
    }

    #[test]
    fn two_tools_folding_to_one_name_are_refused() {
        let text = format!(
            "{}{}{}",
            lock("1.0"),
            entry(
                "aqua:other/demo",
                "2.0",
                "linux-x64",
                "https://x/b",
                &format!("sha256:{SUM}")
            ),
            entry(
                "aqua:other/demo",
                "2.0",
                "windows-x64",
                "https://x/c",
                &format!("sha256:{SUM}")
            ),
        );
        assert!(render(&text).unwrap_err().contains("both generate DEMO_*"));
    }

    #[test]
    fn identifiers_fold_the_last_path_segment() {
        assert_eq!(const_ident("github:lemonade-sdk/lemonade"), "LEMONADE");
        assert_eq!(const_ident("aqua:astral-sh/foo-bar.baz"), "FOO_BAR_BAZ");
        assert_eq!(const_ident("uv"), "UV");
    }

    #[test]
    fn malformed_locks_are_refused_with_the_reason() {
        let checksum = format!("sha256:{SUM}");
        let cases = [
            ("not = [toml".to_owned(), "not valid TOML"),
            ("lockfile_version = 3\n".to_owned(), "no [tools] table"),
            (
                "lockfile_version = 3\n[tools]\n\"github:o/demo\" = \"1.0\"\n".to_owned(),
                "must be an array of entries",
            ),
            (
                "lockfile_version = 3\n[tools]\n\"github:o/demo\" = []\n".to_owned(),
                "has no entries",
            ),
            (
                "lockfile_version = 3\n[[tools.\"github:o/demo\"]]\nbackend = \"x\"\n".to_owned(),
                "entry without a version",
            ),
            (
                lock("1.0").replacen(&format!("checksum = \"{checksum}\"\n"), "", 1),
                "has no checksum",
            ),
        ];
        for (text, reason) in cases {
            let err = render(&text).unwrap_err();
            assert!(err.contains(reason), "expected {reason:?}, got {err:?}");
        }
    }

    #[test]
    fn a_sixty_four_character_digest_that_is_not_hex_is_refused() {
        // Upper case too: the Lemonade adapter compares the lower-case hex it
        // computes with this string, so an upper-case digest never matches.
        for bad in ["z".repeat(64), SUM.to_uppercase()] {
            let text = lock("1.0").replacen(SUM, &bad, 1);
            assert!(
                render(&text)
                    .unwrap_err()
                    .contains("not a sha256 hex digest"),
                "{bad}"
            );
        }
    }

    #[test]
    fn a_tool_missing_linux_is_refused() {
        let text = format!(
            "lockfile_version = 3\n\n{}",
            entry(
                "github:o/demo",
                "1.0",
                "windows-x64",
                "https://x/demo-windows.zip",
                &format!("sha256:{SUM}")
            )
        );
        assert!(
            render(&text)
                .unwrap_err()
                .contains("not locked for linux-x64")
        );
    }

    #[test]
    fn a_platform_rocm_cli_does_not_support_is_refused() {
        for platform in ["macos-x64", "linux-x64\\n#[x]"] {
            let text = format!(
                "{}{}",
                lock("1.0"),
                entry(
                    "github:o/demo",
                    "1.0",
                    platform,
                    "https://x/a",
                    &format!("sha256:{SUM}")
                )
            );
            let err = render(&text).unwrap_err();
            assert!(
                err.contains("only [\"linux-x64\", \"windows-x64\"] are supported"),
                "{platform}: {err}"
            );
        }
    }

    #[test]
    fn a_tool_name_that_could_break_the_generated_source_is_refused() {
        for (tool, reason) in [
            ("github:o/de\\nmo", "has characters a pin cannot carry"),
            ("github:o/de mo", "has characters a pin cannot carry"),
            ("github:o/1demo", "is not a Rust identifier"),
        ] {
            let text = lock("1.0").replace("github:o/demo", tool);
            let err = render(&text).unwrap_err();
            assert!(err.contains(reason), "{tool}: {err}");
        }
    }

    #[test]
    fn identifiers_fold_after_a_backend_prefix_without_a_path() {
        assert_eq!(const_ident("cargo:ripgrep"), "RIPGREP");
    }
}
