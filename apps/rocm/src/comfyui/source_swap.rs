    /// Stopping the swap at every point (see
    /// `interrupted_swap_converges_when_run_again`) with an entry to set
    /// aside: the user's folder is at its own name or its set-aside name,
    /// never both and never gone, and a re-run neither deletes it nor sets
    /// aside the release's own entry that the interrupted run moved in.
    #[test]
    fn interrupted_set_aside_converges_when_run_again() -> Result<()> {
        let mut interrupted_at = 0;
        loop {
            let dir = TestDir::new("interrupt-set-aside");
            let source = used_source_with_colliding_entry(&dir.0);
            let tree = new_release_adding_app(&dir.0, "extract");
            let mut steps = 0;
            let first = install_release_tree_with(&tree, &source, &mut |_| {
                steps += 1;
                if steps > interrupted_at {
                    Err(io::Error::other("interrupted"))
                } else {
                    Ok(())
                }
            });
            if first.is_ok() {
                break;
            }
            assert_eq!(
                user_app_locations(&source).len(),
                1,
                "step {interrupted_at}: the user's app/ must be in exactly one place"
            );

            let report =
                install_release_tree(&new_release_adding_app(&dir.0, "extract-2"), &source)?;

            let locations = user_app_locations(&source);
            assert_eq!(locations.len(), 1, "step {interrupted_at}: {locations:?}");
            assert_eq!(
                report.set_aside,
                [("app".to_owned(), locations[0].clone())],
                "step {interrupted_at}"
            );
            assert_eq!(
                read(&source.join("app/__init__.py")).as_deref(),
                Some("new app"),
                "step {interrupted_at}"
            );
            assert_user_files_intact(&source);
            assert_eq!(report.left_in_place, UNKNOWN_NAMES, "step {interrupted_at}");
            interrupted_at += 1;
        }
        assert!(interrupted_at > 0, "the swap took no steps");
        Ok(())
    }

