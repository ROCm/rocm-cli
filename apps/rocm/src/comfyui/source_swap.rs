    /// On Windows a file another program opened without sharing cannot be
    /// renamed (`ERROR_SHARING_VIOLATION`); the rename is retried until that
    /// program closes it.
    #[cfg(windows)]
    #[test]
    fn rename_waits_for_a_program_holding_the_file() -> Result<()> {
        use std::os::windows::fs::OpenOptionsExt;

        let dir = TestDir::new("held-file");
        let from = dir.0.join("held.py");
        let to = dir.0.join("moved.py");
        fs::write(&from, "code")?;
        let held = fs::OpenOptions::new()
            .read(true)
            .share_mode(0)
            .open(&from)?;
        let error = fs::rename(&from, &to).expect_err("the file is held without sharing");
        assert!(is_held_by_another_program(&error), "{error:?}");
        let release = std::thread::spawn(move || {
            std::thread::sleep(std::time::Duration::from_millis(120));
            drop(held);
        });

        rename_with_retry(&from, &to)?;

        release.join().expect("release thread");
        assert_eq!(read(&to).as_deref(), Some("code"));
        Ok(())
    }
