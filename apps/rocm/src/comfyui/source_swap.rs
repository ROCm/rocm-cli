//! Replacing ComfyUI's code in an existing `source/` folder without touching
//! anything else there.
//!
//! `rocm comfyui start` runs ComfyUI from `source/` without
//! `--user-directory`, `--output-directory` or `--input-directory`, so ComfyUI
//! keeps the user's models, saved workflows, outputs and uploads inside it, and
//! users keep other things there too (a `.git` checkout, a `venv/`,
//! `styles.csv`, logs). A reinstall therefore removes only what a ComfyUI
//! release shipped, moves the new release in around everything else, and
//! never moves, copies or deletes anything under a
//! [`PRESERVED_SOURCE_ENTRIES`] entry.
//!
//! Which top-level names a release shipped is recorded in
//! [`RELEASE_RECORD`] when it is installed, and a reinstall removes those. An
//! entry of the user's that has the name of something the new release adds is
//! renamed out of the way (see [`SwapReport::set_aside`]), not removed. An
//! install that predates the record has nothing to tell release code from the
//! user's, so the names the new release ships are removed there and listed
//! (see [`SwapReport::replaced`]). Every other entry is left in place and
//! reported.
//!
//! The code swap is not atomic, but code can be fetched again: a marker file
//! records an unfinished swap, `start` refuses to run a half-replaced tree,
//! and running the swap again finishes it. `main.py` is removed first and
//! moved in last, so a half-replaced tree never looks complete.

use anyhow::{Context, Result, bail};
use std::collections::BTreeSet;
use std::ffi::{OsStr, OsString};
use std::fmt;
use std::fs;
use std::io;
use std::path::{Component, Path, PathBuf};

/// Entries of the ComfyUI `source/` folder that hold the user's own content
/// and that a reinstall leaves in place.
///
/// `models` (the folder `rocm comfyui models-path` reports), `user` (saved
/// workflows and settings), `output` (generated images; ComfyUI also saves
/// models there), `input` (uploaded images), `custom_nodes` (third-party nodes
/// the user installed, often with their own settings or weights inside),
/// `datasets` (training data; ComfyUI's `folder_paths.py` registers it under
/// the same base folder) and `extra_model_paths.yaml` (user-written; the
/// release ships only the `.example`).
pub(super) const PRESERVED_SOURCE_ENTRIES: &[&str] = &[
    "models",
    "user",
    "output",
    "input",
    "custom_nodes",
    "datasets",
    "extra_model_paths.yaml",
];

/// Written into `source/` before the code swap starts and removed when it
/// finishes. Its presence means a swap was interrupted. It records the
/// [`PRESERVED_SOURCE_ENTRIES`] that existed before that swap began (so a
/// re-run reports what was really the user's rather than what the interrupted
/// run may already have added from the release), the names of the release
/// that run was installing, and the entries of the user's it set aside (so a
/// re-run neither mistakes that release's code for the user's nor the user's
/// entry for release code).
pub(super) const SWAP_MARKER: &str = ".rocm-cli-reinstall-in-progress";

/// The top-level names the installed release shipped, one per line, written
/// with every install. It is what a later reinstall removes.
pub(super) const RELEASE_RECORD: &str = ".rocm-cli-release-entries";

/// Prefix of every file this module writes into `source/`. Such files are
/// never reported as the user's, and a leftover copy in progress is removed.
const CLI_FILE_PREFIX: &str = ".rocm-cli-";
const COPY_IN_PROGRESS_PREFIX: &str = ".rocm-cli-copy-";

/// Inserted between a set-aside entry's name and a timestamp.
pub(super) const SET_ASIDE_INFIX: &str = ".rocm-cli-kept-";

/// Generated by Python from the release's own code, so they go with it.
const GENERATED_FROM_RELEASE: &[&str] = &["__pycache__"];

/// The entry ComfyUI is started from. Removed first and moved in last, so a
/// tree whose swap was cut short never has it.
const ENTRY_POINT: &str = "main.py";

/// Marker lines that are not a preserved entry's name.
const MARKER_RELEASE: &str = "release\t";
const MARKER_SET_ASIDE: &str = "set-aside\t";

/// What a swap did with the existing folder's entries.
#[derive(Debug, Default, PartialEq, Eq)]
pub(super) struct SwapReport {
    /// [`PRESERVED_SOURCE_ENTRIES`] the folder held before the swap began.
    pub(super) kept: Vec<&'static str>,
    /// Top-level entries removed in an install with no usable
    /// [`RELEASE_RECORD`]. Nothing there tells the user's entry from release
    /// code of the same name, so the user is told what went.
    pub(super) replaced: Vec<String>,
    /// Entries of the user's (`(name, new name)`) whose name the new release
    /// started shipping, renamed rather than removed.
    pub(super) set_aside: Vec<(String, String)>,
    /// Top-level entries no ComfyUI release shipped, left exactly as they were.
    pub(super) left_in_place: Vec<String>,
    /// Problems that did not stop the swap but that the user should hear about.
    pub(super) warnings: Vec<String>,
}

/// A release entry that could not be removed, which leaves the swap
/// unfinished. Typed so the caller can name the command that finishes it.
#[derive(Debug)]
pub(super) struct RemovalFailed {
    pub(super) path: PathBuf,
    error: io::Error,
}

impl fmt::Display for RemovalFailed {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "failed to remove {} ({}); close any program using it",
            self.path.display(),
            self.error
        )
    }
}

impl std::error::Error for RemovalFailed {}

/// The [`PRESERVED_SOURCE_ENTRIES`] `source` holds now, in their listed order.
pub(super) fn preserved_entries_present(source: &Path) -> Vec<&'static str> {
    PRESERVED_SOURCE_ENTRIES
        .iter()
        .copied()
        .filter(|name| fs::symlink_metadata(source.join(name)).is_ok())
        .collect()
}

/// What a reinstall started now would report as kept: the entries an
/// interrupted swap recorded, or else the ones present.
pub(super) fn planned_kept(source: &Path) -> Vec<&'static str> {
    if swap_interrupted(source) {
        read_marker(&source.join(SWAP_MARKER)).0.kept
    } else {
        preserved_entries_present(source)
    }
}

/// Whether `source` has a readable record of what its release shipped, which
/// decides whether a reinstall sets aside or replaces an entry named like new
/// release code.
pub(super) fn has_release_record(source: &Path) -> bool {
    read_release_record(source).0.is_some()
}

/// Whether a code swap into `source` was started and did not finish.
pub(super) fn swap_interrupted(source: &Path) -> bool {
    fs::symlink_metadata(source.join(SWAP_MARKER)).is_ok()
}

/// Installs the unpacked release at `new_tree` into `source`.
///
/// Without an existing `source` the release tree is simply moved there. With
/// one, entries of the user's named like new release code are set aside, the
/// entries a ComfyUI release shipped are removed (`main.py` first), the new
/// release's are moved in (`main.py` last), and inside each preserved folder
/// the release only adds what is missing (see [`add_missing_entries`]).
/// Preserved entries, and every entry no release shipped, are never moved,
/// copied, overwritten, deleted or written through when they are symlinks.
pub(super) fn install_release_tree(new_tree: &Path, source: &Path) -> Result<SwapReport> {
    install_release_tree_with(new_tree, source, &mut |_| Ok(()))
}

/// [`install_release_tree`] with `step` called before every filesystem
/// change, so a test can stop the swap at any point the way a crash or a
/// killed process would: without any cleanup running afterwards.
fn install_release_tree_with(
    new_tree: &Path,
    source: &Path,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
) -> Result<SwapReport> {
    install_release_tree_removing_with(new_tree, source, step, &remove_path_io)
}

/// [`install_release_tree_with`] with the removal of a release entry
/// injectable too, so a test can make it fail the way a file held open by
/// another program does, whoever runs the test.
fn install_release_tree_removing_with(
    new_tree: &Path,
    source: &Path,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
    remove: &dyn Fn(&Path) -> io::Result<()>,
) -> Result<SwapReport> {
    let new_names = release_names(new_tree)?;
    if fs::symlink_metadata(source).is_err() {
        let parent = source
            .parent()
            .context("ComfyUI source path has no parent directory")?;
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create {}", parent.display()))?;
        // Recorded inside the tree before it moves, so the one rename that
        // installs the release also installs its record.
        write_atomically(
            &new_tree.join(RELEASE_RECORD),
            &join_lines(&new_names),
            step,
        )?;
        move_release_entry(new_tree, source, step)?;
        return Ok(SwapReport::default());
    }
    if !source.is_dir() {
        bail!("{} exists but is not a folder", source.display());
    }

    let mut report = SwapReport::default();
    let marker = source.join(SWAP_MARKER);
    let mut plan = if swap_interrupted(source) {
        let (plan, warning) = read_marker(&marker);
        report.warnings.extend(warning);
        plan
    } else {
        SwapPlan {
            kept: preserved_entries_present(source),
            ..SwapPlan::default()
        }
    };
    report.kept.clone_from(&plan.kept);
    let (recorded, record_warnings) = read_release_record(source);
    report.warnings.extend(record_warnings);

    // With a record, an entry named like something the new release adds that
    // neither the installed release nor an interrupted run's release shipped
    // is the user's, and is set aside. That is decided before anything of the
    // new release is moved in, and written to the marker before the entry is
    // renamed, so a re-run can tell the two apart.
    if let Some(recorded) = &recorded {
        for name in &new_names {
            let known = recorded.contains(name)
                || plan.release.contains(name)
                || plan.set_aside.iter().any(|(planned, _)| planned == name);
            if !known && fs::symlink_metadata(source.join(name)).is_ok() {
                let new_name = set_aside_name(source, name, &plan, unix_seconds());
                plan.set_aside.push((name.clone(), new_name));
            }
        }
    }
    plan.release.extend(new_names.iter().cloned());
    write_atomically(&marker, &plan.render(), step)?;
    for (name, new_name) in &plan.set_aside {
        let (from, to) = (source.join(name), source.join(new_name));
        if fs::symlink_metadata(&to).is_err() && fs::symlink_metadata(&from).is_ok() {
            step(&from)?;
            rename_with_retry(&from, &to).with_context(|| {
                format!("failed to move {} to {}", from.display(), to.display())
            })?;
        }
        if fs::symlink_metadata(&to).is_ok() {
            report.set_aside.push((
                name.to_string_lossy().into_owned(),
                new_name.to_string_lossy().into_owned(),
            ));
        }
    }

    // What a ComfyUI release shipped here: the installed release's recorded
    // names, plus the new release's and an interrupted run's (which also
    // covers whatever part of them that run already moved in, and an install
    // from before the record existed).
    let mut release_owned: BTreeSet<OsString> = plan.release.clone();
    release_owned.extend(recorded.iter().flatten().cloned());
    release_owned.extend(GENERATED_FROM_RELEASE.iter().map(OsString::from));

    let mut to_remove = Vec::new();
    for entry in read_dir(source)? {
        let name = entry.file_name();
        let text = name.to_string_lossy();
        if is_preserved(&name)
            || text == SWAP_MARKER
            || text == RELEASE_RECORD
            || plan.set_aside.iter().any(|(_, new_name)| *new_name == name)
        {
            continue;
        }
        if release_owned.contains(&name) {
            if recorded.is_none() {
                report.replaced.push(text.clone().into_owned());
            }
            to_remove.push(entry.path());
        } else if text.starts_with(COPY_IN_PROGRESS_PREFIX) {
            to_remove.push(entry.path());
        } else if !text.starts_with(CLI_FILE_PREFIX) {
            report.left_in_place.push(text.into_owned());
        }
    }
    report.replaced.sort();
    report.left_in_place.sort();
    to_remove.sort_by_key(|path| !path.ends_with(ENTRY_POINT));
    for path in to_remove {
        step(&path)?;
        remove(&path).map_err(|error| RemovalFailed {
            path: path.clone(),
            error,
        })?;
    }

    let mut incoming = read_dir(new_tree)?;
    incoming.sort_by_key(|entry| entry.file_name() == ENTRY_POINT);
    for entry in incoming {
        let name = entry.file_name();
        let target = source.join(&name);
        if is_preserved(&name) {
            if fs::symlink_metadata(&target).is_err() {
                move_release_entry(&entry.path(), &target, step)?;
            } else {
                add_missing_entries(&entry.path(), &target, step)?;
            }
        } else if !name.to_string_lossy().starts_with(CLI_FILE_PREFIX) {
            move_release_entry(&entry.path(), &target, step)?;
        }
    }

    write_atomically(&source.join(RELEASE_RECORD), &join_lines(&new_names), step)?;
    step(&marker)?;
    fs::remove_file(&marker).with_context(|| format!("failed to remove {}", marker.display()))?;
    Ok(report)
}

/// What the [`SWAP_MARKER`] records; see there.
#[derive(Debug, Default)]
struct SwapPlan {
    kept: Vec<&'static str>,
    release: BTreeSet<OsString>,
    set_aside: Vec<(OsString, OsString)>,
}

impl SwapPlan {
    fn render(&self) -> String {
        let mut lines: Vec<String> = self.kept.iter().map(|name| (*name).to_owned()).collect();
        lines.extend(
            self.release
                .iter()
                .map(|name| format!("{MARKER_RELEASE}{}", name.to_string_lossy())),
        );
        lines.extend(self.set_aside.iter().map(|(name, new_name)| {
            format!(
                "{MARKER_SET_ASIDE}{}\t{}",
                name.to_string_lossy(),
                new_name.to_string_lossy()
            )
        }));
        lines.join("\n")
    }

    fn parse(text: &str) -> Self {
        let mut plan = Self {
            kept: PRESERVED_SOURCE_ENTRIES
                .iter()
                .copied()
                .filter(|name| text.lines().any(|line| line == *name))
                .collect(),
            ..Self::default()
        };
        for line in text.lines() {
            if let Some(name) = line.strip_prefix(MARKER_RELEASE) {
                if is_single_entry_name(name) {
                    plan.release.insert(OsString::from(name));
                }
            } else if let Some((name, new_name)) = line
                .strip_prefix(MARKER_SET_ASIDE)
                .and_then(|rest| rest.split_once('\t'))
                && is_single_entry_name(name)
                && is_single_entry_name(new_name)
            {
                plan.set_aside
                    .push((OsString::from(name), OsString::from(new_name)));
            }
        }
        plan
    }
}

fn unix_seconds() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}

/// `<name>.rocm-cli-kept-<seconds>`, with a counter added if that is taken in
/// `source` or by another entry this swap sets aside.
fn set_aside_name(source: &Path, name: &OsStr, plan: &SwapPlan, seconds: u64) -> OsString {
    let mut counter = 1;
    loop {
        let mut candidate = name.to_os_string();
        candidate.push(format!("{SET_ASIDE_INFIX}{seconds}"));
        if counter > 1 {
            candidate.push(format!("-{counter}"));
        }
        let taken = fs::symlink_metadata(source.join(&candidate)).is_ok()
            || plan
                .set_aside
                .iter()
                .any(|(_, planned)| *planned == candidate);
        if !taken {
            return candidate;
        }
        counter += 1;
    }
}

fn is_preserved(name: &OsStr) -> bool {
    PRESERVED_SOURCE_ENTRIES
        .iter()
        .any(|preserved| name == *preserved)
}

/// The release's own top-level names, without the preserved ones.
fn release_names(tree: &Path) -> Result<Vec<OsString>> {
    let mut names: Vec<OsString> = read_dir(tree)?
        .into_iter()
        .map(|entry| entry.file_name())
        .filter(|name| !is_preserved(name) && !name.to_string_lossy().starts_with(CLI_FILE_PREFIX))
        .collect();
    names.sort();
    Ok(names)
}

fn join_lines(names: &[OsString]) -> String {
    names
        .iter()
        .map(|name| name.to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("\n")
}

/// Whether `line` names a single entry directly inside `source/`: not empty,
/// `.`, `..`, an absolute path or a path with more than one part.
fn is_single_entry_name(line: &str) -> bool {
    let mut components = Path::new(line).components();
    matches!(
        (components.next(), components.next()),
        (Some(Component::Normal(_)), None)
    )
}

/// The installed release's recorded names, or `None` when there is no usable
/// record: none at all (an install from before it existed, which is not a
/// problem) or an unreadable one, which is reported. A line that does not
/// name a single entry of `source/` is ignored and reported.
fn read_release_record(source: &Path) -> (Option<Vec<OsString>>, Vec<String>) {
    let path = source.join(RELEASE_RECORD);
    match fs::read_to_string(&path) {
        Ok(text) => {
            let mut names = Vec::new();
            let mut warnings = Vec::new();
            for line in text.lines().filter(|line| !line.is_empty()) {
                if !is_single_entry_name(line) {
                    warnings.push(format!(
                        "ignored {line:?} in {}: it does not name an entry of that folder",
                        path.display()
                    ));
                } else if !is_preserved(OsStr::new(line)) {
                    names.push(OsString::from(line));
                }
            }
            (Some(names), warnings)
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => (None, Vec::new()),
        Err(error) => (
            None,
            vec![format!(
                "could not read {} ({error}); entries with the names the new release ships \
                 were replaced instead",
                path.display()
            )],
        ),
    }
}

fn read_dir(path: &Path) -> Result<Vec<fs::DirEntry>> {
    fs::read_dir(path)
        .with_context(|| format!("failed to read {}", path.display()))?
        .collect::<io::Result<Vec<_>>>()
        .with_context(|| format!("failed to read {}", path.display()))
}

/// What an interrupted swap recorded. An unreadable marker yields an empty
/// plan and a warning. That can only make a re-run remove less: an entry the
/// interrupted run moved in is then set aside instead, never deleted.
fn read_marker(marker: &Path) -> (SwapPlan, Option<String>) {
    match fs::read_to_string(marker) {
        Ok(text) => (SwapPlan::parse(&text), None),
        Err(error) => (
            SwapPlan::default(),
            Some(format!(
                "could not read {} ({error}); which of your folders were there before the \
                 interrupted reinstall is unknown, but none of them was touched",
                marker.display()
            )),
        ),
    }
}

/// Writes `path` through a temporary sibling and a rename, so a reader sees
/// either the old contents or the whole new ones.
fn write_atomically(
    path: &Path,
    contents: &str,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
) -> Result<()> {
    let mut temp_name = OsString::from(COPY_IN_PROGRESS_PREFIX);
    temp_name.push(path.file_name().context("path has no file name")?);
    let temp = path.with_file_name(temp_name);
    step(path)?;
    fs::write(&temp, contents).with_context(|| format!("failed to write {}", temp.display()))?;
    rename_with_retry(&temp, path).with_context(|| format!("failed to write {}", path.display()))
}

/// Moves each release entry under `release` that `into` lacks, recursing
/// where both hold a real (not symlinked) directory of the same name. Entries
/// `into` already has are left alone, so the user's copy wins, and a symlinked
/// folder of the user's is never written into: a model folder new in a
/// release appears, but nothing of the user's changes.
fn add_missing_entries(
    release: &Path,
    into: &Path,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
) -> Result<()> {
    if !is_real_dir(release) || !is_real_dir(into) {
        return Ok(());
    }
    for entry in read_dir(release)? {
        let target = into.join(entry.file_name());
        if fs::symlink_metadata(&target).is_err() {
            move_release_entry(&entry.path(), &target, step)?;
        } else {
            add_missing_entries(&entry.path(), &target, step)?;
        }
    }
    Ok(())
}

fn is_real_dir(path: &Path) -> bool {
    fs::symlink_metadata(path).is_ok_and(|metadata| metadata.is_dir())
}

/// Moves a release entry into `source`. Only release content goes through
/// here — never the user's. A rename is all it takes unless the staging folder
/// and `source` are on different filesystems (`source` itself symlinked
/// elsewhere). Only then is the entry copied, without following symlinks, to a
/// temporary name that is renamed into place once complete, so a crash never
/// leaves a truncated release file under the real name.
fn move_release_entry(
    from: &Path,
    to: &Path,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
) -> Result<()> {
    move_release_entry_with(from, to, step, &rename_with_retry)
}

/// [`move_release_entry`] with the rename injectable, so a test can take the
/// copy path without a second filesystem.
fn move_release_entry_with(
    from: &Path,
    to: &Path,
    step: &mut dyn FnMut(&Path) -> io::Result<()>,
    rename: &dyn Fn(&Path, &Path) -> io::Result<()>,
) -> Result<()> {
    step(to)?;
    match rename(from, to) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::CrossesDevices => {
            let mut temp_name = OsString::from(COPY_IN_PROGRESS_PREFIX);
            temp_name.push(to.file_name().context("path has no file name")?);
            let temp = to.with_file_name(temp_name);
            remove_path(&temp)?;
            if let Err(copy_error) = copy_tree_no_follow(from, &temp) {
                remove_path(&temp).ok();
                return Err(copy_error);
            }
            rename(&temp, to).with_context(|| {
                format!("failed to move {} to {}", temp.display(), to.display())
            })?;
            remove_path(from)
        }
        Err(error) => Err(error)
            .with_context(|| format!("failed to move {} to {}", from.display(), to.display())),
    }
}

/// `fs::rename`, retried briefly on Windows while another program holds the
/// file: a scanner that opens freshly unpacked files holds them for a moment.
fn rename_with_retry(from: &Path, to: &Path) -> io::Result<()> {
    #[cfg(windows)]
    {
        let mut delay = std::time::Duration::from_millis(50);
        for _ in 0..5 {
            match fs::rename(from, to) {
                Err(error) if is_held_by_another_program(&error) => {
                    std::thread::sleep(delay);
                    delay *= 2;
                }
                result => return result,
            }
        }
    }
    fs::rename(from, to)
}

/// Access denied, or a sharing or lock violation (`ERROR_SHARING_VIOLATION`,
/// `ERROR_LOCK_VIOLATION`), which std reports with no specific error kind.
#[cfg(windows)]
fn is_held_by_another_program(error: &io::Error) -> bool {
    error.kind() == io::ErrorKind::PermissionDenied || matches!(error.raw_os_error(), Some(32 | 33))
}

/// Copies `from` to `to`, recreating symlinks as symlinks instead of copying
/// what they point at.
fn copy_tree_no_follow(from: &Path, to: &Path) -> Result<()> {
    let file_type = fs::symlink_metadata(from)
        .with_context(|| format!("failed to stat {}", from.display()))?
        .file_type();
    if file_type.is_symlink() {
        let target =
            fs::read_link(from).with_context(|| format!("failed to read {}", from.display()))?;
        return create_symlink(&target, from, to)
            .with_context(|| format!("failed to recreate the symlink {}", to.display()));
    }
    if file_type.is_dir() {
        fs::create_dir(to).with_context(|| format!("failed to create {}", to.display()))?;
        for entry in read_dir(from)? {
            copy_tree_no_follow(&entry.path(), &to.join(entry.file_name()))?;
        }
        return Ok(());
    }
    fs::copy(from, to)
        .map(|_| ())
        .with_context(|| format!("failed to copy {} to {}", from.display(), to.display()))
}

#[cfg(unix)]
fn create_symlink(target: &Path, _original: &Path, link: &Path) -> io::Result<()> {
    std::os::unix::fs::symlink(target, link)
}

#[cfg(windows)]
fn create_symlink(target: &Path, original: &Path, link: &Path) -> io::Result<()> {
    if fs::metadata(original).is_ok_and(|metadata| metadata.is_dir()) {
        std::os::windows::fs::symlink_dir(target, link)
    } else {
        std::os::windows::fs::symlink_file(target, link)
    }
}

/// Removes a file, symlink or directory tree; a missing path is not an error.
/// A symlink is removed itself, never what it points at.
fn remove_path(path: &Path) -> Result<()> {
    remove_path_io(path).with_context(|| format!("failed to remove {}", path.display()))
}

fn remove_path_io(path: &Path) -> io::Result<()> {
    let file_type = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata.file_type(),
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error),
    };
    if file_type.is_dir() {
        fs::remove_dir_all(path)
    } else {
        // A directory symlink on Windows is removed with `remove_dir`.
        fs::remove_file(path).or_else(|error| fs::remove_dir(path).map_err(|_| error))
    }
}

